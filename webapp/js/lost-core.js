/** A free spot for item k (not one of `taken`), picked with rand() in [0, 1). */
export function pickSpot(k, taken, rand = Math.random) {
  const it = ITEM[k];
  if (!it) return -1;
  const ok = [];
  for (let i = 0; i < SPOTS.length; i++) if (it.on.includes(SPOTS[i][3]) && !taken.has(i)) ok.push(i);
  if (!ok.length) return -1;
  // the three places get about the same share whatever their number of spots
  const zones = [...new Set(ok.map((i) => SPOTS[i][4]))];
  const z = zones[Math.floor(rand() * zones.length)];
  const inZone = ok.filter((i) => SPOTS[i][4] === z);
  return inZone[Math.floor(rand() * inZone.length)];
}

